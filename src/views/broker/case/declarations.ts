import type { CaseStepMode } from './caseContext'

// Список ДТ на шаге 3 карточки заявки (редизайн, волна 4а).

/**
 * Можно ли править ДТ из карточки («Заполнить», «XML для КЕДЕН», «Удалить ДТ», «Добавить ДТ», пакетная выгрузка):
 * только пока шаг 3 текущий — декларирование (статус 2) или ДТ подана (статус 3).
 * (баг) Раньше кнопки строк ДТ оставались и в раскрытом пройденном шаге — после выпуска декларант мог удалить ДТ.
 * После шага 3 ДТ только открываются для просмотра.
 */
export const dtEditable = (status: number, mode: CaseStepMode): boolean =>
  mode === 'current' && (status === 2 || status === 3)
