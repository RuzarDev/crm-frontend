// Лестница шагов заявки Импорт 40. Раньше маппинг статус→шаг был скопирован
// в Import40CaseView и Import40ListView; копии разъезжались молча, поэтому
// теперь он один на оба экрана.
//
// Статусы в БД НЕ соответствуют шагам один-к-одному и не меняются:
//   0 — черновик/возврат клиенту      → шаг 1
//   1 — граница пройдена              → шаг 2
//   2 — декларирование                → шаг 3
//   3 — ДТ подана, ждём выпуска       → шаг 3 (выпуск — финал декларирования)
//   4, 5 — СВХ и счёт                 → шаг 4
//   6 — счёт СВХ выставлен, ждём чек  → шаг 5
//   7 — Paid, оплата СВХ подтверждена, ждём счёт/оплату AQNIET → шаг 6 (задача 2.3)
//   8+ — заявка выполнена             → шага нет, это состояние карточки
export const TOTAL_STEPS = 6

export const STEP_TITLES = [
  'Заявка и документы',
  'Граница',
  'Декларирование и выпуск',
  'СВХ и счёт',
  'Оплата СВХ',
  'Оплата услуг AQNIET',
]

export const stepForStatus = (s: number): number =>
  s === 0 ? 1
  : s === 1 ? 2
  : s === 2 || s === 3 ? 3
  : s === 4 || s === 5 ? 4
  : s === 6 ? 5
  : s === 7 ? 6
  : TOTAL_STEPS + 1 // выполнена: вне диапазона, поэтому все шаги рисуются как done

export const isCompleted = (s: number): boolean => s >= 8
